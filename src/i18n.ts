// label = native name (shown in the list), en = English name (searchable too)
export const LANGS = [
  { id: 'zhCN', label: '简体中文', en: 'Chinese (Simplified)' },
  { id: 'zhTW', label: '繁體中文', en: 'Chinese (Traditional)' },
  { id: 'en', label: 'English', en: 'English' },
  { id: 'ja', label: '日本語', en: 'Japanese' },
  { id: 'es', label: 'Español', en: 'Spanish' },
  { id: 'fr', label: 'Français', en: 'French' },
  { id: 'de', label: 'Deutsch', en: 'German' },
  { id: 'nl', label: 'Nederlands', en: 'Dutch' },
] as const

export type Lang = (typeof LANGS)[number]['id']

export const DICT: Record<Lang, Record<LangKey, string>> = { en, zhCN, zhTW, ja, es, fr, nl, de }

// CJK languages get the wide letter-spacing look; alphabet languages get tight spacing
export function isCjk(lang: Lang): boolean {
  return lang === 'zhCN' || lang === 'zhTW' || lang === 'ja'
}

// browser language setting — more reliable than IP geolocation
export function detectLang(): Lang {
  const saved = localStorage.getItem('wheatfield-lang')
  if (saved && saved in DICT) return saved as Lang
  const nav = (navigator.language || 'en').toLowerCase()
  if (nav.startsWith('zh')) {
    return /tw|hk|mo|hant/.test(nav) ? 'zhTW' : 'zhCN'
  }
  if (nav.startsWith('ja')) return 'ja'
  if (nav.startsWith('es')) return 'es'
  if (nav.startsWith('fr')) return 'fr'
  if (nav.startsWith('nl')) return 'nl'
  if (nav.startsWith('de')) return 'de'
  return 'en'
}
